# regen-ids.ps1
# Regenerates solution, feature and component IDs for the DEV package only.
# Run from the repo root on the dev-env branch:
#   powershell -NoProfile -ExecutionPolicy Bypass -File regen-ids.ps1
# Do NOT run on prod-env - changing prod IDs breaks web parts already on prod pages.

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$idPattern = '"id"\s*:\s*"([0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12})"'

# Safety check: refuse to run on prod-env
$branch = (git -C $root rev-parse --abbrev-ref HEAD).Trim()
if ($branch -ne 'dev-env') {
  Write-Host "Current branch is '$branch'. Switch to dev-env first (git switch dev-env)." -ForegroundColor Red
  exit 1
}

# 1. Collect the old IDs from package-solution.json and every component manifest
$sources = @(Get-Item "$root\config\package-solution.json") +
           @(Get-ChildItem "$root\src" -Recurse -Filter '*.manifest.json')
$map = [ordered]@{}
foreach ($f in $sources) {
  foreach ($m in [regex]::Matches((Get-Content -LiteralPath $f.FullName -Raw), $idPattern)) {
    $old = $m.Groups[1].Value.ToLower()
    if (-not $map.Contains($old)) { $map[$old] = [guid]::NewGuid().ToString() }
  }
}

if ($map.Count -eq 0) {
  Write-Host "No IDs found - check you are in the repo root." -ForegroundColor Red
  exit 1
}

# 2. Replace each old ID with its new ID in config, src and sharepoint\assets (covers elements.xml etc.)
#    sharepoint\solution is build output (regenerated by gulp package-solution) and is skipped.
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$targets = Get-ChildItem -LiteralPath "$root\config", "$root\src", "$root\sharepoint\assets" -Recurse -File -ErrorAction SilentlyContinue |
           Where-Object { $_.Extension -in '.json', '.ts', '.tsx', '.js', '.xml' }
foreach ($t in $targets) {
  $text = Get-Content -LiteralPath $t.FullName -Raw
  if ($null -eq $text) { continue }
  $new = $text
  foreach ($old in $map.Keys) {
    $new = [regex]::Replace($new, [regex]::Escape($old), $map[$old], 'IgnoreCase')
  }
  if ($new -ne $text) {
    [IO.File]::WriteAllText($t.FullName, $new, $utf8NoBom)
    Write-Host "Updated: $($t.FullName)"
  }
}

Write-Host "`nOld -> New"
$map.GetEnumerator() | ForEach-Object { Write-Host "$($_.Key) -> $($_.Value)" }
Write-Host "`nNext: review with 'git diff', then update name / zippedPackage / version in config\package-solution.json." -ForegroundColor Yellow
